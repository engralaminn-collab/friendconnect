/**
 * Messages, attachments, reactions, receipts, pins, saved messages,
 * polls/votes and moderation reports.
 */
import {
  boolean,
  datetime,
  index,
  json,
  mysqlTable,
  primaryKey,
  text,
  uniqueIndex,
  varchar,
  int,
} from "drizzle-orm/mysql-core";
import { users } from "./identity";
import { conversations } from "./conversations";
import { media } from "./media";

const now = () => new Date();

export const messages = mysqlTable(
  "messages",
  {
    id: varchar("id", { length: 36 }).primaryKey(),
    conversationId: varchar("conversation_id", { length: 36 })
      .notNull()
      .references(() => conversations.id, { onDelete: "cascade" }),
    /** Nullable for system messages. */
    senderId: varchar("sender_id", { length: 36 }).references(() => users.id, {
      onDelete: "set null",
    }),
    kind: varchar("kind", { length: 16 }).notNull().default("text"),
    body: text("body").notNull(),
    /** Self-reference without an FK: replies may point to deleted messages. */
    replyToId: varchar("reply_to_id", { length: 36 }),
    /** Idempotency nonce generated by the client; unique per sender. */
    clientNonce: varchar("client_nonce", { length: 64 }),
    forwarded: boolean("forwarded").notNull().default(false),
    editedAt: datetime("edited_at", { fsp: 3 }),
    deletedAt: datetime("deleted_at", { fsp: 3 }),
    systemKind: varchar("system_kind", { length: 16 }),
    /** Structured payload for location and contact-card messages. */
    metadata: json("metadata"),
    createdAt: datetime("created_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({
    convCreatedIdx: index("messages_conv_created_idx").on(t.conversationId, t.createdAt),
    senderIdx: index("messages_sender_idx").on(t.senderId),
    replyIdx: index("messages_reply_idx").on(t.replyToId),
    nonceUq: uniqueIndex("messages_sender_nonce_uq").on(t.senderId, t.clientNonce),
  }),
);

export const messageAttachments = mysqlTable(
  "message_attachments",
  {
    id: varchar("id", { length: 36 }).primaryKey(),
    messageId: varchar("message_id", { length: 36 })
      .notNull()
      .references(() => messages.id, { onDelete: "cascade" }),
    mediaId: varchar("media_id", { length: 36 })
      .notNull()
      .references(() => media.id, { onDelete: "restrict" }),
    caption: text("caption"),
    position: int("position").notNull().default(0),
    createdAt: datetime("created_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({
    messageIdx: index("message_attachments_message_idx").on(t.messageId),
    mediaIdx: index("message_attachments_media_idx").on(t.mediaId),
  }),
);

export const messageReactions = mysqlTable(
  "message_reactions",
  {
    messageId: varchar("message_id", { length: 36 })
      .notNull()
      .references(() => messages.id, { onDelete: "cascade" }),
    userId: varchar("user_id", { length: 36 })
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    emoji: varchar("emoji", { length: 32 }).notNull(),
    createdAt: datetime("created_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({
    pk: primaryKey({ columns: [t.messageId, t.userId, t.emoji] }),
    messageIdx: index("message_reactions_message_idx").on(t.messageId),
  }),
);

export const messageReceipts = mysqlTable(
  "message_receipts",
  {
    id: varchar("id", { length: 36 }).primaryKey(),
    messageId: varchar("message_id", { length: 36 })
      .notNull()
      .references(() => messages.id, { onDelete: "cascade" }),
    userId: varchar("user_id", { length: 36 })
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    state: varchar("state", { length: 12 }).notNull(),
    deliveredAt: datetime("delivered_at", { fsp: 3 }),
    readAt: datetime("read_at", { fsp: 3 }),
    updatedAt: datetime("updated_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({
    messageUserUq: uniqueIndex("message_receipts_message_user_uq").on(t.messageId, t.userId),
    userIdx: index("message_receipts_user_idx").on(t.userId),
  }),
);

export const pinnedMessages = mysqlTable(
  "pinned_messages",
  {
    conversationId: varchar("conversation_id", { length: 36 })
      .notNull()
      .references(() => conversations.id, { onDelete: "cascade" }),
    messageId: varchar("message_id", { length: 36 })
      .notNull()
      .references(() => messages.id, { onDelete: "cascade" }),
    pinnedBy: varchar("pinned_by", { length: 36 }).references(() => users.id, {
      onDelete: "set null",
    }),
    pinnedAt: datetime("pinned_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({
    pk: primaryKey({ columns: [t.conversationId, t.messageId] }),
  }),
);

export const savedMessages = mysqlTable(
  "saved_messages",
  {
    id: varchar("id", { length: 36 }).primaryKey(),
    userId: varchar("user_id", { length: 36 })
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    messageId: varchar("message_id", { length: 36 }),
    conversationId: varchar("conversation_id", { length: 36 }),
    threadName: varchar("thread_name", { length: 120 }),
    author: varchar("author", { length: 120 }),
    body: text("body"),
    note: text("note"),
    tag: varchar("tag", { length: 16 }).notNull().default("reference"),
    createdAt: datetime("created_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({ userIdx: index("saved_messages_user_idx").on(t.userId) }),
);

export const polls = mysqlTable(
  "polls",
  {
    id: varchar("id", { length: 36 }).primaryKey(),
    messageId: varchar("message_id", { length: 36 })
      .notNull()
      .references(() => messages.id, { onDelete: "cascade" }),
    question: varchar("question", { length: 500 }).notNull(),
    createdAt: datetime("created_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({ messageUq: uniqueIndex("polls_message_uq").on(t.messageId) }),
);

export const pollOptions = mysqlTable(
  "poll_options",
  {
    id: varchar("id", { length: 36 }).primaryKey(),
    pollId: varchar("poll_id", { length: 36 })
      .notNull()
      .references(() => polls.id, { onDelete: "cascade" }),
    label: varchar("label", { length: 255 }).notNull(),
    position: int("position").notNull().default(0),
  },
  (t) => ({ pollIdx: index("poll_options_poll_idx").on(t.pollId) }),
);

export const pollVotes = mysqlTable(
  "poll_votes",
  {
    optionId: varchar("option_id", { length: 36 })
      .notNull()
      .references(() => pollOptions.id, { onDelete: "cascade" }),
    pollId: varchar("poll_id", { length: 36 })
      .notNull()
      .references(() => polls.id, { onDelete: "cascade" }),
    userId: varchar("user_id", { length: 36 })
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    createdAt: datetime("created_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({
    pk: primaryKey({ columns: [t.optionId, t.userId] }),
    pollIdx: index("poll_votes_poll_idx").on(t.pollId),
  }),
);

export const messageReports = mysqlTable(
  "message_reports",
  {
    id: varchar("id", { length: 36 }).primaryKey(),
    reporterId: varchar("reporter_id", { length: 36 })
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    messageId: varchar("message_id", { length: 36 })
      .notNull()
      .references(() => messages.id, { onDelete: "cascade" }),
    reason: varchar("reason", { length: 120 }).notNull(),
    detail: text("detail"),
    status: varchar("status", { length: 16 }).notNull().default("received"),
    createdAt: datetime("created_at", { fsp: 3 }).notNull().$defaultFn(now),
    updatedAt: datetime("updated_at", { fsp: 3 }).notNull().$defaultFn(now),
  },
  (t) => ({
    reporterIdx: index("message_reports_reporter_idx").on(t.reporterId),
    messageIdx: index("message_reports_message_idx").on(t.messageId),
  }),
);

export type MessageRow = typeof messages.$inferSelect;
export type MessageReceiptRow = typeof messageReceipts.$inferSelect;
